_BY_ID = {p["id"]: p for p in PRESETS}


def find_preset(preset_id: str) -> dict[str, Any] | None:
    return _BY_ID.get(preset_id)


def presets_for(category: str | None = None, kind: str | None = None,
                search: str | None = None) -> list[dict[str, Any]]:
    out = PRESETS
    if category and category != "todas":
        out = [p for p in out if p["category"] == category]
    if kind:
        out = [p for p in out if p["kind"] == kind]
    if search:
        needle = search.lower().strip()
        out = [p for p in out
               if needle in p["name"].lower() or needle in p["prompt"].lower()
               or any(needle in t for t in p["tags"])]
    return out
