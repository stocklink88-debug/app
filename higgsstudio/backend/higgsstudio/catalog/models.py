MODELS: list[dict[str, Any]] = (
    VIDEO_MODELS + IMAGE_MODELS + SPEAK_MODELS + AUDIO_MODELS + TOOL_MODELS
)

_BY_ID = {m["id"]: m for m in MODELS}


def find_model(model_id: str) -> dict[str, Any] | None:
    return _BY_ID.get(model_id)


def model_ids() -> list[str]:
    return list(_BY_ID)


def models_for(family: str | None = None, mode: str | None = None) -> list[dict[str, Any]]:
    out = MODELS
    if family:
        out = [m for m in out if m["family"] == family]
    if mode:
        out = [m for m in out if mode in m.get("modes", [])]
    return out


def default_model(family: str) -> str:
    defaults = {
        "video": "kling-2.5-turbo",
        "image": "soul-2",
        "speak": "flashtalk",
        "audio": "voice-v3",
        "tool": "upscale-image",
    }
    return defaults.get(family, "kling-2.5-turbo")
